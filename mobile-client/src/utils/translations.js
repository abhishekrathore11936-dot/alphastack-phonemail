export function getLocalizedChats(chats, lang) {
  const t = translations[lang] || translations['English'];
  return chats.map(chat => {
    if (chat.id === 1) return { ...chat, name: t.chat1Name, snippet: t.chat1Snippet };
    if (chat.id === 2) return { ...chat, name: t.chat2Name, snippet: t.chat2Snippet };
    if (chat.id === 3) return { ...chat, name: t.chat3Name, snippet: t.chat3Snippet };
    if (chat.type === 'dyn1') return { ...chat, name: t.dyn1Name, snippet: t.dyn1Snippet };
    if (chat.type === 'dyn2') return { ...chat, name: t.dyn2Name, snippet: t.dyn2Snippet };
    if (chat.type === 'dyn3') return { ...chat, name: t.dyn3Name, snippet: t.dyn3Snippet };
    if (chat.type === 'dyn4') return { ...chat, name: t.dyn4Name, snippet: t.dyn4Snippet };
    if (chat.type === 'dyn5') return { ...chat, name: t.dyn5Name, snippet: t.dyn5Snippet };
    return chat;
  });
}
